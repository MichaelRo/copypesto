    @Test("a built-in app allowed for an hour is captured until the hour ends, then excluded again")
    func whenAllowed_thenCapturedUntilItEnds() {
        let now = Date()
        let manager = "com.1password.1password"
        let rules = ExclusionRules(temporaryAllowances: [manager: now.addingTimeInterval(600)])

        #expect(!rules.isExcluded(manager, now: now))
        #expect(rules
            .blockReason(typeIdentifiers: ["public.utf8-plain-text"], frontmostBundleID: manager, now: now) == nil)
        #expect(rules.isExcluded(manager, now: now.addingTimeInterval(601)))
    }

    @Test("an allowance also lets the app's concealed copies through, and never touches another app")
    func whenAllowed_thenItsConcealedCopiesPassAndOthersStayBlocked() {
        let now = Date()
        let manager = "com.bitwarden.desktop"
        let rules = ExclusionRules(
            userAdditions: ["com.example.mine"], temporaryAllowances: [manager: now.addingTimeInterval(600)]
        )

        let concealed = rules.blockReason(
            typeIdentifiers: ["org.nspasteboard.ConcealedType"], frontmostBundleID: manager, now: now
        )
        #expect(concealed == nil)
        #expect(rules.isExcluded("com.apple.keychainaccess", now: now))
        #expect(rules.isExcluded("com.example.mine", now: now))
