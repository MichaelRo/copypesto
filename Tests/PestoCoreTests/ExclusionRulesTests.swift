    @Test("allowances last an hour, are dropped when over, can be revoked and cleared")
    func allowances_lifecycle() {
        let store = ExclusionAllowances(store: AllowanceStore())
        let now = Date()

        let end = store.allow("com.1password.1password", now: now)
        #expect(end == now.addingTimeInterval(3600))
        #expect(store.active(now: now).keys.contains("com.1password.1password"))
        #expect(store.active(now: now.addingTimeInterval(3601)).isEmpty)

        store.allow("com.bitwarden.desktop", now: now)
        store.revoke("com.1password.1password", now: now)
        #expect(Set(store.active(now: now).keys) == ["com.bitwarden.desktop"])

        store.clear()
        #expect(store.active(now: now).isEmpty)
    }

    @Test("an allowance lives in memory only: nothing is written to preferences another process could set")
    func allowances_areNotInPreferences() {
        let defaults = ThrowawayDefaults.make()
        let store = ExclusionAllowances(store: AllowanceStore(), legacyDefaults: defaults)
        store.allow("com.1password.1password")

        #expect(defaults.object(forKey: ExclusionAllowances.legacyDefaultsKey) == nil)
        #expect(defaults.dictionaryRepresentation().keys.allSatisfy { !$0.lowercased().contains("allowance") })
    }

    @Test("an allowance written to preferences by another process is ignored, and removed at launch")
    func allowances_preferencesAreNotTrusted() {
        let defaults = ThrowawayDefaults.make()
        defaults.set(
            ["com.1password.1password": Date.distantFuture.timeIntervalSince1970],
            forKey: ExclusionAllowances.legacyDefaultsKey
        )
        let store = ExclusionAllowances(store: AllowanceStore(), legacyDefaults: defaults)

        #expect(store.active().isEmpty)
        store.clear()
        #expect(defaults.object(forKey: ExclusionAllowances.legacyDefaultsKey) == nil)
    }

    @Test("starting, revoking and clearing an allowance each announce the change")
    func allowances_announceChanges() {
        let store = ExclusionAllowances(store: AllowanceStore())
        let count = Mutex(0)
        let token = NotificationCenter.default.addObserver(
            forName: ExclusionAllowances.didChange, object: nil, queue: nil
        ) { _ in count.withLock { $0 += 1 } }
        defer { NotificationCenter.default.removeObserver(token) }

        store.allow("com.bitwarden.desktop")
        store.revoke("com.bitwarden.desktop")
        store.clear()

        #expect(count.withLock { $0 } >= 3)
    }

    @Test("two handles on one store see the same allowances, as the settings pane and the watcher do")
    func allowances_shareTheirStore() {
        let shared = AllowanceStore()
        ExclusionAllowances(store: shared).allow("com.bitwarden.desktop")

        #expect(ExclusionAllowances(store: shared).active().keys.contains("com.bitwarden.desktop"))
        #expect(ExclusionAllowances(store: AllowanceStore()).active().isEmpty)
    }

    @Test("the length of an allowance is the person's choice, an hour unless they change it")
    func allowances_length() {
        let store = ExclusionAllowances(store: AllowanceStore())
        let now = Date()

        #expect(store.allow("com.bitwarden.desktop", length: .fourHours, now: now) == now.addingTimeInterval(4 * 3600))
        #expect(store.allow("com.bitwarden.desktop", length: .fifteenMinutes, now: now) == now.addingTimeInterval(900))
        #expect(store.allow("com.bitwarden.desktop", now: now) == now.addingTimeInterval(3600), "an hour by default")

        store.allow("com.1password.1password", length: .untilQuit, now: now)
        #expect(store.active(now: now.addingTimeInterval(30 * 24 * 3600)).keys.contains("com.1password.1password"))
        store.clear()
        #expect(store.active(now: now).isEmpty, "an allowance for the session must still end at the next launch")
    }

    private static let concealed = ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"]

    @Test("an allowed app's concealed copy gets through, from any of the apps that may have made it")
    func whenAllowed_thenConcealedCopyFromThatAppPasses() {
        let now = Date()
        let manager = "com.1password.1password"
        let rules = ExclusionRules(temporaryAllowances: [manager: now.addingTimeInterval(600)])

        #expect(rules.blockReason(typeIdentifiers: Self.concealed, sources: [manager], now: now) == nil)
        #expect(rules
            .blockReason(typeIdentifiers: Self.concealed, sources: ["com.apple.Safari", manager], now: now) == nil)
        #expect(rules.keepsConcealedCopy(typeIdentifiers: Self.concealed, sources: [manager], now: now))
    }

    @Test("the concealed copy stays blocked after the allowance, from any other app, and next to a blocked app")
    func whenNotAllowed_thenConcealedStillBlocked() {
        let now = Date()
        let manager = "com.1password.1password"
        let rules = ExclusionRules(temporaryAllowances: [manager: now.addingTimeInterval(600)])

        #expect(rules.blockReason(typeIdentifiers: Self.concealed, sources: [manager], now: now.addingTimeInterval(601))
            == .excludedApp)
        #expect(rules.blockReason(typeIdentifiers: Self.concealed, sources: ["com.apple.Safari"], now: now)
            == .concealedMarker)
        #expect(!rules.keepsConcealedCopy(typeIdentifiers: Self.concealed, sources: ["com.apple.Safari"], now: now))
        #expect(
            rules.blockReason(typeIdentifiers: Self.concealed, sources: [manager, "com.apple.keychainaccess"], now: now)
                == .excludedApp,
            "a second excluded app that is not allowed still blocks"
        )
        #expect(ExclusionRules().blockReason(typeIdentifiers: Self.concealed, sources: ["com.apple.Safari"], now: now)
            == .concealedMarker)
    }

    @Test("an ordinary copy is never flagged as a kept concealed copy")
    func whenNotConcealed_thenNotKeptConcealed() {
        let now = Date()
        let rules = ExclusionRules(temporaryAllowances: ["com.1password.1password": now.addingTimeInterval(600)])
        #expect(!rules.keepsConcealedCopy(
            typeIdentifiers: ["public.utf8-plain-text"], sources: ["com.1password.1password"], now: now
