import AppKit

/// Pasteboard exclusion rules. Append-only by policy — removing a bundle ID requires an ADR.
/// See `decisions/0004-what-is-never-captured.md` and `AGENTS.md` (Security
/// invariants).
public struct ExclusionRules: Sendable {
    /// Marker types that, if present on the pasteboard, indicate we should drop the item silently.
    /// Standard markers from [nspasteboard.org](http://nspasteboard.org) plus Apple's own.
    public static let concealedTypeMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.apple.is-sensitive",
        "Pasteboard generator type",
        // Older identifiers registered at nspasteboard.org.
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "com.agilebits.onepassword",
        "net.antelle.keeweb"
    ]

    /// Bundle IDs of password managers, keychain tools, and similar sensitive sources.
    /// We never ingest from these. Users can add custom entries via Settings → Privacy.
    public static let defaultExcludedBundleIDs: Set<String> = [
        "com.agilebits.onepassword7",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "com.dashlane.dashlanephonefinal",
        "com.apple.keychainaccess",
        "com.lastpass.LastPassMacDesktop",
        "com.callpod.keepersecurity",
        "org.keepassxc.keepassxc",
        "io.macpaw.eccentricapp.Hider5",
        "com.mac-keychain.keychain",
        "com.apple.Passwords",
        "in.sinew.Enpass-Desktop",
        "me.proton.pass.electron",
        "com.hicknhacksoftware.MacPass"
    ]

    /// What Settings shows for each built-in entry. A test keeps this in step with `defaultExcludedBundleIDs`.
    public static let defaultExcludedAppNames: [String: String] = [
        "com.agilebits.onepassword7": "1Password 7",
        "com.1password.1password": "1Password",
        "com.bitwarden.desktop": "Bitwarden",
        "com.dashlane.dashlanephonefinal": "Dashlane",
        "com.apple.keychainaccess": "Keychain Access",
        "com.lastpass.LastPassMacDesktop": "LastPass",
        "com.callpod.keepersecurity": "Keeper",
        "org.keepassxc.keepassxc": "KeePassXC",
        "io.macpaw.eccentricapp.Hider5": "Hider",
        "com.mac-keychain.keychain": "Keychain",
        "com.apple.Passwords": "Passwords",
        "in.sinew.Enpass-Desktop": "Enpass",
        "me.proton.pass.electron": "Proton Pass",
        "com.hicknhacksoftware.MacPass": "MacPass"
    ]

    /// The comma-separated list stored by Settings → Capture: whitespace trimmed, blanks dropped.
    public static func userAdditions(from stored: String) -> Set<String> {
        Set(stored.components(separatedBy: ",").map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty })
    }

    /// The rules as Settings has them now: the built-in list, the person's additions and any timed allowance.
    public static func fromSettings() -> ExclusionRules {
        let raw = AppDefaults.store.value(for: Setting.additionalExcludedBundleIDs)
        return ExclusionRules(
            userAdditions: userAdditions(from: raw),
            temporaryAllowances: ExclusionAllowances().active(),
            keepsRemoteCopies: AppDefaults.store.value(for: Setting.keepsRemoteCopies)
        )
    }

    /// Effective excluded set — defaults plus user-defined entries.
    public let excludedBundleIDs: Set<String>
    private let allowedUntil: [String: Date]
    /// Whether a copy that arrived from another device (Universal Clipboard) is kept. Off in Settings by default.
    public let keepsRemoteCopies: Bool

    /// - Parameter temporaryAllowances: built-in apps the person has switched off for a while, with when each ends
    ///   (`ExclusionAllowances`). Only a built-in entry can be allowed. Password managers mark every copy as concealed,
    ///   so an allowance also lets that app's concealed copies through (stored hidden), and only while it runs.
    public init(
        userAdditions: Set<String> = [], temporaryAllowances: [String: Date] = [:], keepsRemoteCopies: Bool = false
    ) {
        self.keepsRemoteCopies = keepsRemoteCopies
        self.excludedBundleIDs = Self.defaultExcludedBundleIDs.union(userAdditions)
        self.allowedUntil = temporaryAllowances.filter { Self.defaultExcludedBundleIDs.contains($0.key) }
    }

    private func isAllowedNow(_ bundleID: String, now: Date) -> Bool {
        excludedBundleIDs.contains(bundleID) && (allowedUntil[bundleID].map { $0 > now } ?? false)
    }

    public func isExcluded(_ bundleID: String, now: Date = .now) -> Bool {
        guard excludedBundleIDs.contains(bundleID) else { return false }
        if let until = allowedUntil[bundleID], until > now { return false }
        return true
    }

    public enum BlockReason: String, Sendable, Codable {
        case excludedApp
        case concealedMarker
        case remoteCopy
    }

    /// Why a copy is dropped, or nil to keep it. An excluded app wins over a concealed marker.
    public func blockReason(typeIdentifiers: [String], frontmostBundleID: String?, now: Date = .now) -> BlockReason? {
        blockReason(typeIdentifiers: typeIdentifiers, sources: [frontmostBundleID], now: now)
    }

    /// Why a copy is dropped, judged over every app that may have made it (the frontmost one and those that were in
    /// front
    /// a moment before), or nil to keep it. Any excluded source blocks; a concealed marker blocks unless one of the
    /// sources is an app the person has allowed right now.
    /// A copy from another device is judged by its markers alone: the Mac app in front did not make it.
    public func blockReason(
        typeIdentifiers: [String], sources: [String?], isRemote: Bool = false, now: Date = .now
    )
    -> BlockReason? {
        if isRemote, !keepsRemoteCopies { return .remoteCopy }
        let sources = isRemote ? [] : sources
        let ids = sources.compactMap(\.self)
        if ids.contains(where: { isExcluded($0, now: now) }) { return .excludedApp }
        let concealed = typeIdentifiers.contains(where: Self.concealedTypeMarkers.contains)
        if concealed, !keepsConcealedCopy(typeIdentifiers: typeIdentifiers, sources: sources, now: now) {
            return .concealedMarker
        }
        return nil
    }

    /// True when the copy is concealed and is kept anyway because an app the person allowed made it.
    public func keepsConcealedCopy(typeIdentifiers: [String], sources: [String?], now: Date = .now) -> Bool {
        concealedKeepEnd(typeIdentifiers: typeIdentifiers, sources: sources, now: now) != nil
    }

    /// When the allowance that lets a concealed copy in ends: the earliest end among the allowed apps that may have
    /// made it, so a copy is never kept longer than the shortest allowance that could explain it. Nil when the copy
    /// is not concealed or no allowed app made it.
    public func concealedKeepEnd(typeIdentifiers: [String], sources: [String?], now: Date = .now) -> Date? {
        guard typeIdentifiers.contains(where: Self.concealedTypeMarkers.contains) else { return nil }
        return sources.compactMap(\.self).filter { isAllowedNow($0, now: now) }.compactMap { allowedUntil[$0] }.min()
    }

    /// True iff the pasteboard contents should be dropped silently.
    /// - Parameters:
    ///   - typeIdentifiers: Raw type strings present on the pasteboard.
    ///   - frontmostBundleID: Captured at the moment `changeCount` incremented.
    public func shouldIgnore(typeIdentifiers: [String], frontmostBundleID: String?) -> Bool {
        blockReason(typeIdentifiers: typeIdentifiers, frontmostBundleID: frontmostBundleID) != nil
    }

    /// Convenience: accept the AppKit-typed array directly.
    public func shouldIgnore(types: [NSPasteboard.PasteboardType], frontmostBundleID: String?) -> Bool {
        shouldIgnore(typeIdentifiers: types.map(\.rawValue), frontmostBundleID: frontmostBundleID)
    }
}
